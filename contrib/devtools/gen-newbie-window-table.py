"""Generate src/gridcoin/accrual/newbie_window.h.

The inputs are the debug.log files of a mainnet and a testnet node run with
-debug=accrual while it connects the superblocks of the window. For each
research account that a superblock creates, the node logs:

    ... accrual account not found for CPID <cpid>. Creating account with accrual
    <accrual> from Accrual Correction = <correction>, Accrual Delta = <delta>,
    superblock height = <height>, ...

Each table holds every (height, CPID, correction) with a nonzero correction. The
script stops if a log holds conflicting corrections for the same CPID and
height.

Usage:
    gen-newbie-window-table.py <mainnet debug.log> <testnet debug.log> > src/gridcoin/accrual/newbie_window.h
"""

import re
import sys

LINE = re.compile(
    r"accrual account not found for CPID ([0-9a-f]{32})\. Creating account with accrual (-?\d+) "
    r"from Accrual Correction = (-?\d+), Accrual Delta = (-?\d+), superblock height = (\d+)")

HEADER = """\
// Copyright (c) 2026 The Gridcoin developers
// Distributed under the MIT/X11 software license, see the accompanying
// file COPYING or https://opensource.org/licenses/mit-license.php.

// Generated by contrib/devtools/gen-newbie-window-table.py. Do not edit.

#ifndef GRIDCOIN_ACCRUAL_NEWBIE_WINDOW_H
#define GRIDCOIN_ACCRUAL_NEWBIE_WINDOW_H

#include <cstdint>

namespace GRC {
//!
//! \\brief A newbie accrual correction that a network applied to a new research
//! account in the newbie correction window. See TallySuperblockAccrual() in
//! gridcoin/tally.cpp.
//!
struct NewbieWindowEntry
{
    int64_t m_height;     //!< Height of the superblock that created the account.
    const char* m_cpid;   //!< CPID of the account, in hex.
    int64_t m_correction; //!< Correction applied, in units of 1 / COIN.
};
"""

TABLE = """
//!
//! \\brief The nonzero newbie accrual corrections of {network}, ordered by height
//! and CPID.
//!
static constexpr NewbieWindowEntry {name}[] = {{
"""

FOOTER = """\
} // namespace GRC

#endif // GRIDCOIN_ACCRUAL_NEWBIE_WINDOW_H
"""


def read_corrections(path):
    entries = {}

    with open(path, encoding="utf-8", errors="replace") as log:
        for line in log:
            match = LINE.search(line)

            if not match:
                continue

            cpid = match.group(1)
            accrual, correction, delta, height = (int(match.group(i)) for i in range(2, 6))

            if accrual != correction + delta:
                sys.exit(f"{path}: inconsistent log line for CPID {cpid} at height {height}: {line.strip()}")

            if correction == 0:
                continue

            key = (height, cpid)

            if entries.get(key, correction) != correction:
                sys.exit(f"{path}: conflicting corrections for CPID {cpid} at height {height}")

            entries[key] = correction

    if not entries:
        sys.exit(f"{path}: no nonzero newbie accrual correction found; was the log written with -debug=accrual?")

    return entries


def write_table(network, name, entries):
    keys = sorted(entries)

    sys.stdout.write(TABLE.format(network=network, name=name))

    for height, cpid in keys:
        sys.stdout.write(f'    {{{height}, "{cpid}", {entries[(height, cpid)]}}},\n')

    sys.stdout.write("};\n")

    print(f"{network}: {len(keys)} {'entry' if len(keys) == 1 else 'entries'}", file=sys.stderr)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)

    mainnet, testnet = read_corrections(sys.argv[1]), read_corrections(sys.argv[2])

    sys.stdout.write(HEADER)
    write_table("mainnet", "MAINNET_NEWBIE_WINDOW", mainnet)
    write_table("testnet", "TESTNET_NEWBIE_WINDOW", testnet)
    sys.stdout.write(FOOTER)


if __name__ == "__main__":
    main()
